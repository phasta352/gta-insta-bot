"""Turns a post's slides into a vertical 9:16 Reel (MP4, H.264 + AAC) with ffmpeg.

Layout: each 4:5 slide sits in the Reels "safe zone" on a branded 1080x1920 background,
slides glide in from the right, the current slide slowly zooms, a progress bar runs along
the top, and an outro card asks people to follow. Music comes from assets/music/ (your own
licensed tracks) or, if that folder is empty, an original track generated by bot/music.py.
"""
import random
import subprocess
from pathlib import Path

from PIL import Image, ImageDraw

from . import design, music
from .config import ROOT

RW, RH = 1080, 1920
FPS = 30
SLIDE_Y = 200            # top of the 4:5 slide (keeps it clear of Instagram's caption area)
GLIDE = 0.45             # seconds for a slide to glide in


def _ease(t):
    return 1 - (1 - t) ** 3


def _background(settings):
    # same colour and gradient as the post graphics
    c = design._hex(settings["design"]["background"])
    bg = Image.new("RGB", (RW, RH), c[:3])
    d = ImageDraw.Draw(bg)
    for y in range(RH):
        a = int(60 * (y / RH))
        d.line([(0, y), (RW, y)], fill=tuple(max(0, v - a // 3) for v in c[:3]))
    return bg


def _outro(settings, handle):
    img = _background(settings).convert("RGBA")
    d = ImageDraw.Draw(img)
    colors = {k: design._hex(settings["design"][k]) for k in ("accent", "text", "muted")}
    logo_path = ROOT / settings["design"].get("logo", "")
    y = 640
    if logo_path.is_file():
        logo = Image.open(logo_path).convert("RGBA")
        logo.thumbnail((620, 420))
        img.alpha_composite(logo, ((RW - logo.width) // 2, y))
        y += logo.height + 90
    else:
        f = design.bold_font(90)
        name = settings["page"]["name"]
        d.text(((RW - d.textlength(name, font=f)) // 2, y), name, font=f, fill=colors["text"])
        y += 200
    f1 = design.bold_font(56)
    line1 = f"Follow {handle}" if handle else "Follow for more"
    d.text(((RW - d.textlength(line1, font=f1)) // 2, y), line1, font=f1, fill=colors["accent"])
    f2 = design.regular_font(40)
    line2 = settings["page"].get("tagline", "for daily news")
    d.text(((RW - d.textlength(line2, font=f2)) // 2, y + 90), line2, font=f2, fill=colors["muted"])
    return img.convert("RGB")


def _durations(n_slides, texts):
    """Seconds per slide: the cover gets 3.5 s, story slides get reading time for their text."""
    out = [3.5]
    for t in texts:
        out.append(min(6.5, max(3.0, 1.8 + len(t) / 45)))
    return out[:n_slides] + [2.8]   # + outro


def pick_music(duration, seed, out_dir: Path, prefer: str = "") -> str:
    """A track from assets/music (or a specific one whose file name contains `prefer`),
    else an original generated track."""
    folder = ROOT / "assets" / "music"
    tracks = sorted(p for p in folder.glob("*") if p.suffix.lower() in (".mp3", ".m4a", ".wav", ".aac")) \
        if folder.is_dir() else []
    if prefer:
        match = [t for t in tracks if prefer.lower() in t.name.lower()]
        if not match:
            raise FileNotFoundError(f"No music file in assets/music matching '{prefer}'")
        return str(match[0])
    if tracks:
        return str(random.Random(seed).choice(tracks))
    return music.make_track(duration + 0.5, out_dir / f"music-{seed}.wav", seed=seed)


def make_reel(headline, category, source, slides, settings, handle, out_path: Path, seed: int = 0,
              background=None, music_name: str = "") -> Path:
    """Build a vertical Reel: cover, story slides ([{title, text}]) and an outro card, with music."""
    work = out_path.parent
    work.mkdir(parents=True, exist_ok=True)
    stem = out_path.stem
    with design.reel_format():
        frames = [design.render(headline, category, source, settings, handle, work / f"{stem}-r0.jpg",
                                swipe=False, background=background)]
        for n, sl in enumerate(slides, start=2):
            frames.append(design.render_slide(n, len(slides) + 1, sl["title"], sl["text"], source, settings,
                                              handle, work / f"{stem}-r{n - 1}.jpg", background=background))
    images = [Image.open(p).convert("RGB") for p in frames]
    durations = _durations(len(images), [sl["text"] for sl in slides])
    total_s = sum(durations)
    outro = _outro(settings, handle)
    accent = design._hex(settings["design"]["accent"])[:3]
    track = pick_music(total_s, seed, work, prefer=music_name)
    print(f"[bot] Reel music: {Path(track).name}", flush=True)

    cmd = ["ffmpeg", "-y", "-loglevel", "error",
           "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{RW}x{RH}", "-r", str(FPS), "-i", "-",
           "-i", track,
           "-c:v", "libx264", "-preset", "veryfast", "-crf", "20", "-pix_fmt", "yuv420p",
           "-af", f"afade=t=in:d=0.3,afade=t=out:st={max(0.0, total_s - 1.5):.2f}:d=1.5",
           "-c:a", "aac", "-b:a", "160k", "-ar", "48000",
           "-shortest", "-movflags", "+faststart", str(out_path)]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)

    n = len(images)
    for i in range(n + 1):
        is_outro = i == n
        for f in range(int(durations[i] * FPS)):
            t = f / FPS
            if is_outro:
                frame = Image.blend(images[-1], outro, _ease(t / GLIDE)) if t < GLIDE else outro
            else:
                # very slow zoom on the current card
                z = 1 + 0.02 * (t / durations[i])
                cw, ch = int(RW * z), int(RH * z)
                cur = images[i].resize((cw, ch), Image.BILINEAR).crop(
                    ((cw - RW) // 2, (ch - RH) // 2, (cw - RW) // 2 + RW, (ch - RH) // 2 + RH))
                if i > 0 and t < GLIDE:   # glide in from the right, pushing the previous card out
                    p = _ease(t / GLIDE)
                    frame = Image.new("RGB", (RW, RH))
                    frame.paste(images[i - 1], (int(-RW * p), 0))
                    frame.paste(cur, (int(RW * (1 - p)), 0))
                else:
                    frame = cur
                # progress bar: one segment per card, like Stories
                d = ImageDraw.Draw(frame)
                gap, x0, width = 10, 60, RW - 120
                seg = (width - gap * (n - 1)) / n
                for k in range(n):
                    sx = x0 + k * (seg + gap)
                    d.rounded_rectangle([sx, 150, sx + seg, 158], radius=4, fill=(70, 85, 105))
                    done = 1 if k < i else (t / durations[i] if k == i else 0)
                    if done > 0:
                        d.rounded_rectangle([sx, 150, sx + seg * min(1, done), 158], radius=4, fill=accent)
            proc.stdin.write(frame.tobytes())
    proc.stdin.close()
    if proc.wait() != 0:
        raise RuntimeError("ffmpeg failed while making the Reel")
    return out_path
